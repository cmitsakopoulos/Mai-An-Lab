#!/usr/bin/env python3
"""Generates lib/core/nfc_table.dart: the data `unicodedata.normalize("NFC")`
works from, for lib/core/nfc.dart (filepath_utils.normalize_nfc). Dart has
no Unicode normaliser.

  * canonical combining classes (non-zero), as ranges of equal class;
  * one-level canonical decompositions (`unicodedata.decomposition` without a
    <tag>); Hangul syllables are handled arithmetically in Dart;
  * the full composition exclusions among the two-character decompositions
    (the characters NFC never recomposes), found by asking Python.

    ~/miniconda3/bin/python tool/gen_nfc_table.py
"""
import os
import sys
import unicodedata as u

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "nfc_table.dart")

ccc_ranges = []  # (lo, hi, ccc)
decomp = {}      # code point -> tuple of code points (one level)
excluded = []

for o in range(sys.maxunicode + 1):
    if 0xD800 <= o <= 0xDFFF:
        continue
    c = chr(o)
    k = u.combining(c)
    if k:
        if ccc_ranges and ccc_ranges[-1][1] == o - 1 and ccc_ranges[-1][2] == k:
            ccc_ranges[-1] = (ccc_ranges[-1][0], o, k)
        else:
            ccc_ranges.append((o, o, k))
    if 0xAC00 <= o <= 0xD7A3:
        continue
    d = u.decomposition(c)
    if not d or d.startswith("<"):
        continue
    parts = tuple(int(x, 16) for x in d.split())
    decomp[o] = parts
    if len(parts) == 2 and u.normalize("NFC", "".join(map(chr, parts))) != c:
        excluded.append(o)


def chunks(xs, n):
    for i in range(0, len(xs), n):
        yield xs[i:i + n]


with open(OUT, "w") as f:
    f.write("// GENERATED by tool/gen_nfc_table.py from Python's unicodedata "
            f"{u.unidata_version}. Do not edit.\n\n")
    f.write("/// Non-zero canonical combining classes: [lo, hi, class, ...] "
            "(inclusive ranges).\n")
    f.write("const kCccRanges = <int>[\n")
    for lo, hi, k in ccc_ranges:
        f.write(f"  0x{lo:x}, 0x{hi:x}, {k},\n")
    f.write("];\n\n")
    f.write("/// One-level canonical decompositions: [code point, length, parts...]\n"
            "/// (Hangul syllables excluded).\n")
    f.write("const kCanonicalDecomp = <int>[\n")
    for o, parts in sorted(decomp.items()):
        f.write(f"  0x{o:x}, {len(parts)}, " + ", ".join(f"0x{p:x}" for p in parts) + ",\n")
    f.write("];\n\n")
    f.write("/// Two-part decompositions that NFC does not recompose (the\n"
            "/// composition exclusions).\n")
    f.write("const kCompositionExcluded = <int>[\n")
    for row in chunks(excluded, 8):
        f.write("  " + ", ".join(f"0x{o:x}" for o in row) + ",\n")
    f.write("];\n")
print(len(ccc_ranges), "ccc ranges,", len(decomp), "decompositions,", len(excluded), "exclusions")
