#!/usr/bin/env python3
"""Generates lib/core/nfkd_fold_table.dart: what Python's
`"".join(c for c in unicodedata.normalize("NFKD", s) if not unicodedata.combining(c))`
does to each BMP character (metadata_enrich._fold). Dart has no Unicode
normaliser. Hangul syllables are decomposed arithmetically in Dart instead.

    ~/miniconda3/bin/python tool/gen_nfkd_table.py
"""
import os
import unicodedata as u

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "nfkd_fold_table.dart")

pairs, comb = [], []
start = None
for o in range(0x80, 0x10000):
    c = chr(o)
    is_comb = bool(u.combining(c))
    if is_comb and start is None:
        start = o
    if not is_comb and start is not None:
        comb.append((start, o - 1))
        start = None
    if is_comb or 0xAC00 <= o <= 0xD7A3 or 0xD800 <= o <= 0xDFFF:
        continue
    d = "".join(x for x in u.normalize("NFKD", c) if not u.combining(x))
    if d != c:
        pairs.append((o, d))


def lit(s: str) -> str:
    return "".join(f"\\u{{{ord(ch):x}}}" for ch in s)


with open(OUT, "w") as f:
    f.write("// GENERATED by tool/gen_nfkd_table.py from Python's unicodedata "
            f"{u.unidata_version}. Do not edit.\n\n")
    f.write("/// Code points with a non-zero canonical combining class, as "
            "inclusive ranges [lo, hi, lo, hi, ...].\n")
    f.write("const kCombiningRanges = <int>[\n")
    for lo, hi in comb:
        f.write(f"  0x{lo:x}, 0x{hi:x},\n")
    f.write("];\n\n")
    f.write("/// NFKD of each BMP character with combining marks removed, for the\n"
            "/// characters where that differs from the character itself.\n")
    f.write("const kNfkdFold = <int, String>{\n")
    for o, d in pairs:
        f.write(f"  0x{o:x}: '{lit(d)}',\n")
    f.write("};\n")
print(len(pairs), "pairs,", len(comb), "combining ranges")
