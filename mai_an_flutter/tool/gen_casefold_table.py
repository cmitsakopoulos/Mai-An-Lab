#!/usr/bin/env python3
"""Generates lib/core/py_unicode_tables.dart: the Unicode data behind
Python's `str.lower()`, `str.casefold()` and `str.isdecimal()` / `int()`
that Dart lacks or has from older Unicode data (Dart's toLowerCase misses
letters added since, such as Georgian Mtavruli).

  kPyLower         every code point whose lower() is not itself (full
                   mappings: İ -> i̇); Final_Sigma is applied in Dart.
  kPyTitle         every code point whose title() is not itself (ß -> Ss,
                   Ǆ -> ǅ, ...).
  kPyCasefold      every code point whose casefold() is not itself
                   (ß -> ss, ς -> σ, Cherokee, ...).
  kDecimalZeros    the zero of each block of ten Nd digits (str.isdecimal is
                   true exactly for these blocks; int() reads them as 0-9).
  kDigitNotDecimal the code points str.isdigit() also accepts (superscripts,
                   circled digits, ...), which int() rejects.

    ~/miniconda3/bin/python tool/gen_casefold_table.py
"""
import os
import sys
import unicodedata as u

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "py_unicode_tables.dart")

lower = [(c, chr(c).lower()) for c in range(sys.maxunicode + 1)
         if not 0xD800 <= c <= 0xDFFF and chr(c).lower() != chr(c)]
title = [(c, chr(c).title()) for c in range(sys.maxunicode + 1)
         if not 0xD800 <= c <= 0xDFFF and chr(c).title() != chr(c)]
fold = [(c, chr(c).casefold()) for c in range(sys.maxunicode + 1)
        if not 0xD800 <= c <= 0xDFFF and chr(c).casefold() != chr(c)]
zeros = [c for c in range(sys.maxunicode + 1)
         if chr(c).isdecimal() and u.decimal(chr(c)) == 0]
assert all(all(chr(z + i).isdecimal() and u.decimal(chr(z + i)) == i for i in range(10)) for z in zeros)
assert sum(1 for c in range(sys.maxunicode + 1) if chr(c).isdecimal()) == 10 * len(zeros)
digits = [c for c in range(sys.maxunicode + 1)
          if chr(c).isdigit() and not chr(c).isdecimal()]


def lit(s: str) -> str:
    return "".join(f"\\u{{{ord(ch):x}}}" for ch in s)


with open(OUT, "w") as f:
    f.write("// GENERATED by tool/gen_casefold_table.py from Python's unicodedata "
            f"{u.unidata_version}. Do not edit.\n\n")
    for name, doc, table in (("kPyLower", "str.lower()", lower),
                             ("kPyTitle", "str.title()", title),
                             ("kPyCasefold", "str.casefold()", fold)):
        f.write(f"/// Code points whose `{doc}` is not themselves.\n")
        f.write(f"const {name} = <int, String>{{\n")
        for c, s in table:
            f.write(f"  0x{c:x}: '{lit(s)}',\n")
        f.write("};\n\n")
    f.write("/// The zero of each block of ten decimal digits (Unicode Nd).\n")
    f.write("const kDecimalZeros = <int>[\n")
    for z in zeros:
        f.write(f"  0x{z:x},\n")
    f.write("];\n\n")
    f.write("/// Code points `str.isdigit()` accepts beyond the decimal digits.\n")
    f.write("const kDigitNotDecimal = <int>{\n")
    for c in digits:
        f.write(f"  0x{c:x},\n")
    f.write("};\n")
print(OUT, len(lower), len(fold), len(zeros), len(digits))
