#!/usr/bin/env python3
"""Generates lib/core/py_unicode_tables.dart: the Unicode data behind
Python's `str.casefold()` and `str.isdecimal()` / `int()` that Dart lacks.

  kCasefoldExtra   code points whose casefold differs from their lower()
                   (ß -> ss, ς -> σ, Cherokee, ...); every other character
                   casefolds to its lower case.
  kDecimalZeros    the zero of each block of ten Nd digits (str.isdecimal is
                   true exactly for these blocks; int() reads them as 0-9).

    ~/miniconda3/bin/python tool/gen_casefold_table.py
"""
import os
import sys
import unicodedata as u

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "py_unicode_tables.dart")

extra = [(c, chr(c).casefold()) for c in range(sys.maxunicode + 1)
         if chr(c).casefold() != chr(c).lower()]
zeros = [c for c in range(sys.maxunicode + 1)
         if chr(c).isdecimal() and u.decimal(chr(c)) == 0]
assert all(all(chr(z + i).isdecimal() and u.decimal(chr(z + i)) == i for i in range(10)) for z in zeros)
assert sum(1 for c in range(sys.maxunicode + 1) if chr(c).isdecimal()) == 10 * len(zeros)


def lit(s: str) -> str:
    return "".join(f"\\u{{{ord(ch):x}}}" for ch in s)


with open(OUT, "w") as f:
    f.write("// GENERATED by tool/gen_casefold_table.py from Python's unicodedata "
            f"{u.unidata_version}. Do not edit.\n\n")
    f.write("/// Code points whose `str.casefold()` differs from `str.lower()`.\n")
    f.write("const kCasefoldExtra = <int, String>{\n")
    for c, s in extra:
        f.write(f"  0x{c:x}: '{lit(s)}',\n")
    f.write("};\n\n")
    f.write("/// The zero of each block of ten decimal digits (Unicode Nd).\n")
    f.write("const kDecimalZeros = <int>[\n")
    for z in zeros:
        f.write(f"  0x{z:x},\n")
    f.write("];\n")
print(OUT, len(extra), len(zeros))
