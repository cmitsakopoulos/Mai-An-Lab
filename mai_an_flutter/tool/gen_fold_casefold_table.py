#!/usr/bin/env python3
"""Generates lib/core/nfkd_casefold_table.dart: the characters for which
web_research._fold,

    "".join(ch for ch in unicodedata.normalize("NFKD", s).casefold()
            if not unicodedata.combining(ch))

is not what py_text.dart's existing pieces give when chained
(nfkdStrip, then pyCasefold, then combining marks dropped). Those pieces
drop combining marks before casefolding, so U+0345 (which casefolds to ι)
is lost, and nfkdStrip leaves characters outside the BMP alone. For these
code points the table holds Python's answer.

    ~/miniconda3/bin/python tool/gen_fold_casefold_table.py
"""
import os
import sys
import unicodedata as u

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "nfkd_casefold_table.dart")


def fold(s):
    s = u.normalize("NFKD", s).casefold()
    return "".join(ch for ch in s if not u.combining(ch))


def dart_combining(ch):  # py_text.dart's _isCombining: BMP ranges from 0x80
    return 0x80 <= ord(ch) < 0x10000 and bool(u.combining(ch))


def dart_nfkd_strip(c):  # py_text.dart's nfkdStrip on one character
    o = ord(c)
    if dart_combining(c):
        return ""
    if 0xAC00 <= o <= 0xD7A3:
        return u.normalize("NFKD", c)
    if 0x80 <= o < 0x10000:
        return "".join(x for x in u.normalize("NFKD", c) if not u.combining(x))
    return c


def dart_chain(c):
    return "".join(x for x in dart_nfkd_strip(c).casefold() if not dart_combining(x))


ex = []
for o in range(sys.maxunicode + 1):
    if 0xD800 <= o <= 0xDFFF:
        continue
    c = chr(o)
    if fold(c) != dart_chain(c):
        ex.append((o, fold(c)))


def lit(s):
    return "".join(f"\\u{{{ord(ch):x}}}" for ch in s)


with open(OUT, "w", encoding="utf-8") as f:
    f.write("// GENERATED by tool/gen_fold_casefold_table.py from Python's unicodedata "
            f"{u.unidata_version}. Do not edit.\n\n")
    f.write("/// Code points whose NFKD + casefold + combining-strip differs from\n")
    f.write("/// nfkdStrip then pyCasefold, with Python's result.\n")
    f.write("const Map<int, String> kNfkdCasefoldExceptions = {\n")
    for o, v in ex:
        f.write(f"  0x{o:X}: '{lit(v)}',\n")
    f.write("};\n")
print(len(ex), "exceptions")
