#!/usr/bin/env python3
"""Generates lib/core/py_re_tables.dart: what Python's `re` (str patterns)
means by the pieces the ported patterns use, so lib/core/py_re.dart can
spell them out for Dart's RegExp, whose Unicode tables and case folding
differ.

  * `\\w`: every code point `re.match(r"\\w", c)` accepts, as ranges;
  * `\\s`: every code point `re.match(r"\\s", c)` accepts (checked against
    the list py_text.dart's pyIsSpace hard-codes);
  * `re.IGNORECASE` for each ASCII letter: every code point a literal
    letter matches (sre lowers the subject with `_sre.unicode_tolower` and
    adds `re._compiler._equivalences`, so 'i' also takes 'İ' and 'ı', 's'
    takes 'ſ', 'k' the Kelvin sign).

    ~/miniconda3/bin/python tool/gen_py_re_tables.py
"""
import os
import re
import string
import sys
import unicodedata

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "py_re_tables.dart")

word_ranges = []
space = []
for o in range(sys.maxunicode + 1):
    if 0xD800 <= o <= 0xDFFF:
        continue
    c = chr(o)
    if re.match(r"\w", c):
        if word_ranges and word_ranges[-1][1] == o - 1:
            word_ranges[-1][1] = o
        else:
            word_ranges.append([o, o])
    if re.match(r"\s", c):
        space.append(o)

PY_TEXT_SPACE = (list(range(0x09, 0x0E)) + list(range(0x1C, 0x21)) + [0x85, 0xA0, 0x1680]
                 + list(range(0x2000, 0x200B)) + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000])
assert space == PY_TEXT_SPACE, space

letters = {}
for ch in string.ascii_lowercase:
    pat = re.compile(ch, re.I)
    letters[ch] = [o for o in range(sys.maxunicode + 1)
                   if not 0xD800 <= o <= 0xDFFF and pat.match(chr(o))]

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// GENERATED by tool/gen_py_re_tables.py from Python "
            f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).\n")
    f.write("// Do not edit.\n\n")
    f.write("/// Python's `\\w` for str patterns, as inclusive code point ranges\n")
    f.write("/// (lo, hi, lo, hi, …).\n")
    f.write("const List<int> kPyWordRanges = [\n")
    for lo, hi in word_ranges:
        f.write(f"  0x{lo:X}, 0x{hi:X},\n")
    f.write("];\n\n")
    f.write("/// Under `re.IGNORECASE`, the code points each ASCII letter matches.\n")
    f.write("const Map<String, List<int>> kPyIgnoreCaseLetters = {\n")
    for ch, cps in letters.items():
        f.write(f"  '{ch}': [{', '.join(f'0x{o:X}' for o in cps)}],\n")
    f.write("};\n")

print(f"{len(word_ranges)} word ranges; letters with extra matches:",
      {k: [hex(o) for o in v if chr(o).lower() != k and chr(o) != k.upper()] for k, v in letters.items()
       if len(v) > 2})
